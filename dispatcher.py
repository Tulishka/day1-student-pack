ASK_LOCATION_RE = re.compile(
    r"каком\s+кабинет|каком\s+помещени|каком\s+месте|какой\s+кабинет|где\s+именно",
    re.IGNORECASE,
)

ONLINE_SERVICE_RE = re.compile(
    r"дневник|портал|сайт|вход\w*|парол|логин|уч[её]тн\w*|школьн\w*\s+сервис\w*|из\s+дома|дома\b",
    re.IGNORECASE,
)

