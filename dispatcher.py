def _extract_json(content):
    """Достаёт JSON-объект из ответа модели, в том числе из ```json ... ```."""
    text = (content or "").strip()
    if not text:
        raise ValueError("Модель вернула пустой ответ")
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError(f"Модель вернула не JSON: {text[:120]!r}")
    return json.loads(match.group(0))


def classify(text):
    if os.environ.get("DISPATCHER_DEMO", "1") == "1":
        return {"type": "issue", "category": "другое", "priority": "обычный", "question": ""}

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": text},
    ]
    try:
        response = chat(messages)
        content = response["choices"][0]["message"]["content"]
        data = _extract_json(content)
    except (RuntimeError, ValueError, KeyError, TypeError, json.JSONDecodeError):
        return {"type": "chat", "reply": "Извините, сервер пока недоступен, обратитесь к преподавателю"}

    if not isinstance(data, dict):
        raise ValueError("Ответ модели должен быть JSON-объектом")

    # Вежливость / сообщения без проблемы — короткий ответ вместо классификации.
    is_chat = data.get("type") == "chat" or (
        data.get("reply") and not data.get("category")
    )
    if is_chat:
        reply = str(data.get("reply") or "").strip() or "Всегда пожалуйста."
        return {"type": "chat", "reply": reply[:200]}

    if data.get("category") not in CATEGORIES:
        raise ValueError("Модель вернула неизвестную категорию")
    if data.get("priority") not in PRIORITIES:
        raise ValueError("Модель вернула неизвестный приоритет")
    if not isinstance(data.get("question"), str):
        raise ValueError("Уточняющий вопрос должен быть строкой")

    question = data["question"].strip()
    followup_count = text.count(FOLLOWUP_MARK)
    has_specific = bool(SPECIFIC_LOCATION_RE.search(text))
    # Не более двух уточняющих вопросов за диалог.
    if followup_count >= 2:
        question = ""
    # Место уже точное — не переспрашиваем.
    if question and has_specific and ASK_LOCATION_RE.search(question):
        question = ""
    # Вопрос о кабинете не нужен для онлайн-сервисов и учёток.
    if question and ASK_LOCATION_RE.search(question) and ONLINE_SERVICE_RE.search(text):
        question = ""
    needs_place = (
        data.get("category") in {"техника", "помещение"}
        or (data.get("category") == "сеть" and not ONLINE_SERVICE_RE.search(text))
    )
    if re.search(r"консультаци|оформлени|совет|как\s+(?:сделать|оформить)|подсказать", text, re.IGNORECASE):
        needs_place = False
    already_asked_place = bool(re.search(
        r"каком(?:\s+именно)?\s+(?:кабинет|помещен|месте)|какой\s+кабинет",
        text,
        re.IGNORECASE,
    ))
    # Пользователь уже ответил на уточнение — не повторяем тот же вопрос.
    if followup_count > 0 and re.search(r"Ответ на уточняющий вопрос:\s*\S", text):
        already_asked_place = already_asked_place or bool(re.search(r"кабинет|месте|помещени", text, re.IGNORECASE))
    if (
        not question
        and followup_count < 2
        and needs_place
        and not has_specific
        and not ONLINE_SERVICE_RE.search(text)
        and not already_asked_place
    ):
        question = (
            "В каком именно кабинете?"
            if re.search(r"кабинет|зал[еу]|помещени|коридор", text, re.IGNORECASE)
            else "В каком кабинете?"
        )

    return {
        "type": "issue",
        "category": data["category"],
        "priority": data["priority"],
        "question": question,
    }